"""Перенос данных: mysqldump -> SQL-файл с COPY для PostgreSQL (этап 1).

Целевая схема берётся из начального changelog Liquibase (0002-tables.sql и 0003-foreign-keys.sql),
поэтому файл загружается в базу, которую уже создал Liquibase.

Что делает:
- приводит значения к типам PostgreSQL: bit/tinyint(1) -> boolean, «нулевые» даты -> NULL,
  убирает символ NUL из текста;
- пропускает колонки MySQL, которых нет в целевой схеме (суррогатные id join-таблиц и т.п.);
- ДО генерации проверяет всё, на чём упала бы загрузка: NOT NULL, длину varchar/char,
  значения enum-колонок (CHECK ... IN), диапазоны smallint/integer, внешние ключи
  (с учётом регистронезависимой collation ci), уникальность PK. Нарушения — в отчёте,
  при нарушениях файл не пишется (флаг --force пишет всё равно);
- в конце выставляет счётчики identity-колонок по max(id).

Использование:
  python -I dump_to_pg.py <дамп.sql> <changelog/changes> <выходной .sql> [--force]

Загрузка (FK-триггеры на время COPY отключаются через session_replication_role,
нужен суперпользователь или GRANT SET ON PARAMETER session_replication_role):
  psql -v ON_ERROR_STOP=1 -d <база> -f <выходной .sql>
"""
import collections
import os
import re
import sys

sys.stdout.reconfigure(encoding='utf-8')
dump_path, changes_dir, out_path = sys.argv[1:4]
force = '--force' in sys.argv

# ---------- целевая схема ----------
tables = {}
cur = None
for line in open(os.path.join(changes_dir, '0002-tables.sql'), encoding='utf-8'):
    m = re.match(r'CREATE TABLE "?(\w+)"? \(', line)
    if m:
        cur = {'name': m.group(1), 'cols': [], 'pk': []}
        tables[cur['name']] = cur
        continue
    if cur is None:
        continue
    s = line.strip().rstrip(',')
    if s.startswith(');'):
        cur = None
        continue
    m = re.match(r'primary key \((.*)\)', s)
    if m:
        cur['pk'] = [c.strip(' "') for c in m.group(1).split(',')]
        continue
    if s.startswith(('unique', 'constraint', 'check')):
        continue
    m = re.match(r'"?(\w+)"? (\w+(?: precision)?)(?:\((\d+)(?:,\d+)?\))?(.*)$', s)
    name, typ, length, rest = m.group(1), m.group(2).lower(), m.group(3), m.group(4)
    enum = re.search(r"in \(((?:'[^']*',?)+)\)", rest)
    cur['cols'].append({'name': name, 'type': typ, 'len': int(length) if length else None,
                        'notnull': 'not null' in rest, 'ci': 'collate ci' in rest,
                        'identity': 'generated by default as identity' in rest,
                        'enum': set(re.findall(r"'([^']*)'", enum.group(1))) if enum else None})
fks = []
for line in open(os.path.join(changes_dir, '0003-foreign-keys.sql'), encoding='utf-8'):
    m = re.match(r'ALTER TABLE "?(\w+)"? ADD CONSTRAINT (\w+) FOREIGN KEY \((.*?)\) REFERENCES "?(\w+)"? \((.*?)\)', line)
    if m:
        fks.append({'table': m.group(1), 'name': m.group(2), 'cols': [c.strip(' "') for c in m.group(3).split(',')],
                    'ref': m.group(4), 'refcols': [c.strip(' "') for c in m.group(5).split(',')]})

# ---------- токенизатор mysqldump ----------
TOKEN = re.compile(r"""
    (?P<null>NULL)
  | (?P<str>(?:_binary\s+|_utf8mb4\s*|_utf8mb3\s*)?'(?:[^'\\]|\\.|'')*')
  | (?P<hex>0x[0-9A-Fa-f]*)
  | (?P<bits>b'[01]*')
  | (?P<num>[-+]?[0-9][0-9.eE+-]*)
  | (?P<open>\()
  | (?P<close>\))
""", re.X | re.S)
UNESC = {'0': '\0', "'": "'", '"': '"', 'b': '\b', 'n': '\n', 'r': '\r', 't': '\t', 'Z': '\x1a', '\\': '\\',
         '%': '\\%', '_': '\\_'}
ESC_RE = re.compile(r"\\(.)|''", re.S)


def unescape(s):
    body = s[s.index("'") + 1:-1]
    if '\\' not in body and "''" not in body:
        return body
    return ESC_RE.sub(lambda m: "'" if m.group(0) == "''" else UNESC.get(m.group(1), m.group(1)), body)


def parse_rows(values_sql):
    row = None
    for m in TOKEN.finditer(values_sql):
        k = m.lastgroup
        if k == 'open':
            row = []
        elif k == 'close':
            yield row
            row = None
        elif row is None:
            continue
        elif k == 'null':
            row.append(None)
        elif k == 'str':
            row.append(unescape(m.group()))
        elif k == 'bits':
            row.append(str(int(m.group()[2:-1] or '0', 2)))
        elif k == 'hex':
            row.append(bytes.fromhex(m.group()[2:]).decode('latin1'))
        else:
            row.append(m.group())


# ---------- конвертация ----------
INT_RANGE = {'smallint': (-32768, 32767), 'integer': (-2 ** 31, 2 ** 31 - 1), 'bigint': (-2 ** 63, 2 ** 63 - 1)}
problems = collections.defaultdict(list)
fixed = collections.Counter()  # однозначные исправления, сделанные при загрузке


def problem(kind, where, detail):
    if len(problems[(kind, where)]) < 5:
        problems[(kind, where)].append(detail)
    else:
        problems[(kind, where)].append(None)


def convert(col, v, where):
    if v is None:
        return None
    t = col['type']
    if t == 'boolean':
        if v in ('\x01', '1', 'true', 'TRUE', 'b1'):
            return 't'
        if v in ('\x00', '0', '', 'false', 'FALSE'):
            return 'f'
        problem('boolean', where, repr(v))
        return v
    if t in INT_RANGE:
        try:
            n = int(float(v))
        except ValueError:
            problem('не число', where, repr(v)[:40])
            return v
        lo, hi = INT_RANGE[t]
        if not lo <= n <= hi:
            problem('вне диапазона ' + t, where, n)
        return str(n)
    if t.startswith('timestamp') or t in ('date', 'time'):
        if v.startswith('0000-00-00'):
            return None
        return v
    if t in ('varchar', 'char', 'text'):
        if '\0' in v:
            v = v.replace('\0', '')
        if col['len'] and len(v) > col['len']:
            problem(f"длиннее {t}({col['len']})", where, f'{len(v)} символов')
        if col['enum'] is not None and v not in col['enum']:
            if v.strip() in col['enum']:
                fixed[f'пробелы вокруг enum-значения: {where}'] += 1
                v = v.strip()
            else:
                problem('значение не из enum', where, v)
        return v
    return v


def copy_escape(v):
    if v is None:
        return '\\N'
    return v.replace('\\', '\\\\').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')


# ---------- порядок элементов коллекций (sort_order) ----------
# В MySQL списки читались без ORDER BY, и порядок задавал индекс, по которому шла выборка
# по владельцу: составной ключ (владелец, значение...) -> по значению, иначе по id строки,
# иначе в порядке вставки. Сущности теперь хранят порядок явно (@OrderColumn sort_order),
# и загрузчик заполняет его так, чтобы сайт показывал списки как раньше.
# Ключ владельца берём из самого baseline: первичный ключ таблицы коллекции — (владелец..., sort_order).
# Так загрузчик не зависит от текущего маппинга сущностей, который уходит вперёд от baseline.
order_key = {tn: [c for c in t['pk'] if c != 'sort_order'] for tn, t in tables.items()
             if 'sort_order' in t['pk'] and any(c['name'] == 'sort_order' for c in t['cols'])}


def mysql_sort_cols(tn, key_cols):
    """Колонки, по которым MySQL фактически отдавал строки владельца."""
    for idx_cols in mysql_keys.get(tn, []):  # PRIMARY первым, затем UNIQUE
        if idx_cols[:len(key_cols)] == key_cols and len(idx_cols) > len(key_cols):
            return idx_cols[len(key_cols):]
    return ['id'] if 'id' in mysql_cols[tn] else []


def typed(v):
    if v is None:
        return (0, '')
    return (1, int(v)) if re.fullmatch(r'-?\d+', v) else (2, v.lower())


# ---------- проход по дампу ----------
mysql_cols = {}
mysql_keys = collections.defaultdict(list)
data = {}  # таблица -> список строк уже в целевом порядке колонок
sort_src = collections.defaultdict(list)  # таблица -> (ключ владельца, ключ сортировки MySQL, № строки)
skipped_tables, dropped_cols = set(), collections.defaultdict(set)
copy_cols = {}  # таблица -> колонки в COPY (в порядке строк data)
cur_create = None
with open(dump_path, encoding='utf-8') as fh:
    for line in fh:
        m = re.match(r'CREATE TABLE `(\w+)`', line)
        if m:
            cur_create = m.group(1)
            mysql_cols[cur_create] = []
            continue
        if cur_create and line.startswith('  `'):
            mysql_cols[cur_create].append(re.match(r'  `([^`]+)`', line).group(1))
            continue
        if cur_create:
            km = re.match(r'\s+(PRIMARY KEY|UNIQUE KEY `\w+`) \((.*)\)', line)
            if km:
                cols = re.findall(r'`([^`]+)`', km.group(2))
                if km.group(1) == 'PRIMARY KEY':
                    mysql_keys[cur_create].insert(0, cols)
                else:
                    mysql_keys[cur_create].append(cols)
                continue
        if line.startswith(')'):
            cur_create = None
            continue
        m = re.match(r'INSERT INTO `(\w+)` VALUES ', line)
        if not m:
            continue
        tn = m.group(1)
        if tn not in tables:
            skipped_tables.add(tn)
            continue
        src = mysql_cols[tn]
        # identity-колонки, которых не было в MySQL (id для порядка в коллекциях), в COPY не
        # передаём: PostgreSQL выдаст значения в порядке строк дампа, то есть в порядке MySQL.
        target = copy_cols.setdefault(tn, [c for c in tables[tn]['cols']
                                           if not (c['identity'] and c['name'] not in src)])
        idx = {c: i for i, c in enumerate(src)}
        for c in src:
            if c not in {x['name'] for x in target}:
                dropped_cols[tn].add(c)
        rows = data.setdefault(tn, [])
        computed = {'sort_order'} if tn in order_key and 'sort_order' not in src else set()
        if computed:
            kc = order_key[tn]
            sc = mysql_sort_cols(tn, kc)
        for r in parse_rows(line[m.end():]):
            out = []
            for col in target:
                i = idx.get(col['name'])
                v = r[i] if i is not None else None
                v = convert(col, v, f"{tn}.{col['name']}")
                if v is None and col['notnull'] and col['name'] not in computed:
                    problem('NULL в NOT NULL', f"{tn}.{col['name']}", r[0] if r else '?')
                out.append(v)
            if computed:
                sort_src[tn].append((tuple(r[idx[c]] for c in kc), tuple(typed(r[idx[c]]) for c in sc), len(rows)))
            rows.append(out)

# sort_order: позиция строки среди строк того же владельца в порядке MySQL
for tn, items in sort_src.items():
    pos_col = next(i for i, c in enumerate(copy_cols[tn]) if c['name'] == 'sort_order')
    counters = collections.Counter()
    for owner, _, rowno in sorted(items, key=lambda x: (x[0], x[1], x[2])):
        data[tn][rowno][pos_col] = str(counters[owner])
        counters[owner] += 1
    fixed[f"sort_order по {('индексу MySQL ' + ','.join(mysql_sort_cols(tn, order_key[tn]))) if mysql_sort_cols(tn, order_key[tn]) else 'порядку строк дампа'}: {tn}"] += len(items)

# Дальше работаем с теми колонками, что реально идут в COPY (полный список — для setval).
all_cols = {tn: t['cols'] for tn, t in tables.items()}
for tn, cols in copy_cols.items():
    tables[tn]['cols'] = cols


# ---------- проверки целостности ----------
def key(col, v):
    return v.lower() if (v is not None and col['ci']) else v


for tn, t in tables.items():
    if t['pk'] and tn in data:
        pos = [next(i for i, c in enumerate(t['cols']) if c['name'] == p) for p in t['pk']]
        if len(pos) == sum(1 for c in t['cols'] if not c['identity']):
            # PK из всех колонок (коллекция-множество): полные дубли — одна и та же запись
            seen, uniq = set(), []
            for r in data[tn]:
                k = tuple(key(t['cols'][i], r[i]) for i in pos)
                if k not in seen:
                    seen.add(k)
                    uniq.append(r)
            if len(uniq) != len(data[tn]):
                fixed[f'полные дубли строк: {tn}'] += len(data[tn]) - len(uniq)
                data[tn] = uniq
        cnt = collections.Counter(tuple(key(t['cols'][i], r[i]) for i in pos) for r in data[tn])
        for k, n in cnt.items():
            if n > 1:
                problem('дубль PK', tn, k)

# Связи, где строку с висячей ссылкой безопасно отбросить: запись без родителя бессмысленна.
# То же делает вторая часть очистки MySQL (db/2026-11-18-pg-prep-2-drop-unused-data.sql).
DROP_ORPHANS = {('verification_token', ('user_id',))}

for f in fks:
    ct, pt = tables[f['table']], tables[f['ref']]
    if (f['table'], tuple(f['cols'])) in DROP_ORPHANS:
        ci_ = [next(i for i, c in enumerate(ct['cols']) if c['name'] == x) for x in f['cols']]
        pi_ = [next(i for i, c in enumerate(pt['cols']) if c['name'] == x) for x in f['refcols']]
        parent = {tuple(key(pt['cols'][i], r[i]) for i in pi_) for r in data.get(f['ref'], [])}
        before = len(data.get(f['table'], []))
        data[f['table']] = [r for r in data.get(f['table'], [])
                            if any(r[i] is None for i in ci_) or tuple(key(ct['cols'][i], r[i]) for i in ci_) in parent]
        if before != len(data[f['table']]):
            fixed[f"строки с висячей ссылкой: {f['table']}.{','.join(f['cols'])}"] += before - len(data[f['table']])
    ci = [next(i for i, c in enumerate(ct['cols']) if c['name'] == x) for x in f['cols']]
    pi = [next(i for i, c in enumerate(pt['cols']) if c['name'] == x) for x in f['refcols']]
    parent = {tuple(key(pt['cols'][i], r[i]) for i in pi) for r in data.get(f['ref'], [])}
    for r in data.get(f['table'], []):
        k = tuple(key(ct['cols'][i], r[i]) for i in ci)
        if any(x is None for x in k):
            continue
        if k not in parent:
            problem('висячая ссылка', f"{f['table']}.{','.join(f['cols'])} -> {f['ref']}", k)

# ---------- отчёт ----------
print(f'таблиц с данными: {len(data)}, строк: {sum(len(v) for v in data.values())}')
print(f'таблицы дампа без целевой таблицы (пропущены): {", ".join(sorted(skipped_tables)) or "нет"}')
print('колонки дампа без целевой колонки (пропущены):')
for tn in sorted(dropped_cols):
    print(f'  {tn}: {", ".join(sorted(dropped_cols[tn]))}')
if fixed:
    print('\nисправлено при загрузке:')
    for k, n in sorted(fixed.items()):
        print(f'  {k}: {n}')
if problems:
    print(f'\nПРОБЛЕМЫ ({len(problems)}):')
    for (kind, where), items in sorted(problems.items()):
        shown = [repr(x) for x in items if x is not None]
        more = sum(1 for x in items if x is None)
        print(f'  [{kind}] {where}: {", ".join(shown)}' + (f' и ещё {more}' if more else ''))
    if not force:
        print('\nФайл не записан. Исправьте данные или запустите с --force.')
        sys.exit(1)

# ---------- запись ----------
with open(out_path, 'w', encoding='utf-8', newline='\n') as out:
    out.write('-- Сгенерировано db/pg-migration/load/dump_to_pg.py из ' + os.path.basename(dump_path) + '\n')
    out.write('\\set ON_ERROR_STOP on\nBEGIN;\nSET session_replication_role = replica;\n\n')
    for tn, t in tables.items():
        rows = data.get(tn)
        if not rows:
            continue
        cols = ', '.join(f'"{c["name"]}"' for c in t['cols'])
        out.write(f'COPY "{tn}" ({cols}) FROM stdin;\n')
        for r in rows:
            out.write('\t'.join(copy_escape(v) for v in r) + '\n')
        out.write('\\.\n\n')
    out.write('SET session_replication_role = DEFAULT;\n\n-- счётчики identity\n')
    for tn in tables:
        for c in all_cols[tn]:
            if c['identity']:
                out.write(f"SELECT setval(pg_get_serial_sequence('\"{tn}\"', '{c['name']}'), "
                          f"COALESCE(MAX(\"{c['name']}\"), 1), MAX(\"{c['name']}\") IS NOT NULL) FROM \"{tn}\";\n")
    out.write('\nCOMMIT;\nANALYZE;\n')
print(f'записано: {out_path}')
