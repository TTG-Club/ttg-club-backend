package club.dnd5.portal.model.charactersheet;

/**
 * Состояние права на редактирование чужого листа. Отказа нет: отказ и отзыв запись удаляют,
 * и попросить право заново можно сразу.
 */
public enum CharacterSheetEditorStatus {
	/** Запрос отправлен, владелец ещё не ответил. */
	PENDING,
	/** Владелец разрешил: лист открывается и сохраняется редактором. */
	APPROVED
}
